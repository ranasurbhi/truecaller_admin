class Campaign {
  final String name;
  final String id;
  final String status;
  final String duration;
  final String team;
  final double progress;
  final double performance;

  Campaign({
    required this.name,
    required this.id,
    required this.status,
    required this.duration,
    required this.team,
    required this.progress,
    required this.performance,
  });
}
